#!/usr/bin/env python3
"""
Emit a macless-haystack devices.json for our existing beacon key pair.

macless-haystack stores only the private key in devices.json and derives the
advertising key (P-224 X coordinate) and its SHA-256 from it, so the key pair
generated by scripts/keygen.py plugs straight in.

Usage:
    python scripts/haystack_devices.py [name]
"""

import base64
import hashlib
import json
import pathlib
import sys

from cryptography.hazmat.primitives.asymmetric import ec

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> int:
    name = sys.argv[1] if len(sys.argv) > 1 else "beacon"

    priv_hex = (ROOT / "keys" / f"{name}.priv.hex").read_text().strip()
    priv = bytes.fromhex(priv_hex)
    assert len(priv) == 28, "private key must be 28 bytes"

    curve = ec.SECP224R1()
    pub = ec.derive_private_key(int.from_bytes(priv, "big"), curve).public_key()
    adv = pub.public_numbers().x.to_bytes(28, "big")

    priv_b64 = base64.b64encode(priv).decode()
    adv_b64 = base64.b64encode(adv).decode()
    s256_b64 = base64.b64encode(hashlib.sha256(adv).digest()).decode()

    # Schema taken from macless-haystack generate_keys.py.
    devices = [{
        "id": 1,
        "colorComponents": [0, 1, 0, 1],
        "name": name,
        "privateKey": priv_b64,
        "icon": "",
        "isActive": True,
        "additionalKeys": [],
    }]

    out = ROOT / "keys" / f"{name}_devices.json"
    out.write_text(json.dumps(devices, indent=2) + "\n")

    print(f"private key  (base64): {priv_b64}")
    print(f"adv key      (base64): {adv_b64}")
    print(f"hashed adv   (base64): {s256_b64}")
    print(f"wrote {out.relative_to(ROOT)}")
    print()
    print("This file contains the private key - import it into the frontend and"
          " never commit or share it.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
