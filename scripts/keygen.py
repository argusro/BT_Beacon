#!/usr/bin/env python3
"""
Generate (once) and render the rotating Apple Find My key ring for a tag.

Design: keys are created **once** per tag and then reused forever. Re-flashing
the same device must not rotate its identity, so `--if-missing` (used by the
PlatformIO pre-build hook) regenerates nothing and only refreshes the C header.

Imports of `cryptography` are lazy: rendering an existing ring works with the
PlatformIO Python, which does not ship the library.

Outputs
  src/beacon_keys.h      C array of N advertising keys (28 bytes each)
  keys/<name>_keys.json  private + advertising key per slot (SECRET)
"""

import argparse
import base64
import hashlib
import json
import pathlib
import sys
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parent.parent


# --------------------------------------------------------------------------- #
# pure stdlib: rendering and store access
# --------------------------------------------------------------------------- #
def hexdump(data: bytes, per_line: int = 14) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    return "\n".join(lines)


def hash_b64(adv: bytes) -> str:
    return base64.b64encode(hashlib.sha256(adv).digest()).decode()


def header_text(keys: list[dict]) -> str:
    entries = ["  {\n" + hexdump(k["adv"]) + "\n  }," for k in keys]
    return (
        "// Generated by scripts/keygen.py -- do not edit by hand.\n"
        f"// {len(keys)} rotating Apple Find My advertising keys (P-224 X coordinates).\n"
        "#pragma once\n\n#include <stdint.h>\n\n"
        f"#define BEACON_KEY_COUNT {len(keys)}\n\n"
        f"static const uint8_t BEACON_KEYS[BEACON_KEY_COUNT][28] = {{\n"
        + "\n".join(entries) + "\n};\n"
    )


def write_header(path: pathlib.Path, keys: list[dict]) -> bool:
    """Write the header only when its content changes; returns True if written."""
    text = header_text(keys)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def load_store(path: pathlib.Path) -> tuple[list[dict], dict]:
    data = json.loads(path.read_text())
    keys = [{"priv": bytes.fromhex(e["priv"]), "adv": bytes.fromhex(e["adv"])}
            for e in data["keys"]]
    return keys, data


# --------------------------------------------------------------------------- #
# needs cryptography
# --------------------------------------------------------------------------- #
def adv_from_private(priv: bytes) -> bytes:
    from cryptography.hazmat.primitives.asymmetric import ec

    pub = ec.derive_private_key(int.from_bytes(priv, "big"), ec.SECP224R1()).public_key()
    return pub.public_numbers().x.to_bytes(28, "big")


def generate_keys(count: int, seed_private: bytes | None = None) -> list[dict]:
    from cryptography.hazmat.primitives.asymmetric import ec

    keys: list[dict] = []
    if seed_private and len(seed_private) == 28:
        keys.append({"priv": seed_private, "adv": adv_from_private(seed_private)})

    while len(keys) < count:
        priv = ec.generate_private_key(ec.SECP224R1()).private_numbers().private_value
        priv_bytes = priv.to_bytes(28, "big")
        keys.append({"priv": priv_bytes, "adv": adv_from_private(priv_bytes)})
    return keys


# --------------------------------------------------------------------------- #
# cli
# --------------------------------------------------------------------------- #
def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-n", "--count", type=int, default=96,
                        help="number of keys in the ring (default 96 = 24h at 15 min)")
    parser.add_argument("--fresh", action="store_true",
                        help="replace an existing ring (rotates the tag's identity)")
    parser.add_argument("--name", default="beacon",
                        help="tag name; writes keys/<name>_keys.json")
    parser.add_argument("--header", default="src/beacon_keys.h",
                        help="C header to generate for the firmware")
    parser.add_argument("--no-header", action="store_true",
                        help="only write keys/<name>_keys.json")
    parser.add_argument("--if-missing", action="store_true",
                        help="reuse the existing ring if present (idempotent)")
    args = parser.parse_args()

    if args.count < 2:
        parser.error("--count must be at least 2")

    store_path = ROOT / "keys" / f"{args.name}_keys.json"
    header_path = ROOT / args.header

    # Idempotent path: an existing ring is never regenerated.
    if store_path.exists() and (args.if_missing or not args.fresh):
        keys, data = load_store(store_path)
        if not args.no_header:
            changed = write_header(header_path, keys)
            print(f"keys: tag '{args.name}' -> {args.header} "
                  f"({'updated' if changed else 'up to date'}, {len(keys)} slots)")
        else:
            print(f"keys: tag '{args.name}' exists ({len(keys)} slots)")
        return 0

    # Slot 0 reuses the original key so pre-upgrade reports stay reachable.
    seed = None
    legacy = ROOT / "keys" / "beacon.priv.hex"
    if args.name == "beacon" and legacy.exists() and not args.fresh:
        seed = bytes.fromhex(legacy.read_text().strip())

    try:
        keys = generate_keys(args.count, seed)
    except ImportError:
        print("!! cryptography is not available in this Python; run keygen with a "
              "Python that has it (e.g. `python scripts/keygen.py --name "
              f"{args.name}`)", file=sys.stderr)
        return 1

    (ROOT / "keys").mkdir(exist_ok=True)
    store = {
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "name": args.name,
        "curve": "secp224r1",
        "keys": [{"priv": k["priv"].hex(),
                  "adv": k["adv"].hex(),
                  "hash_b64": hash_b64(k["adv"])} for k in keys],
    }
    store_path.write_text(json.dumps(store, indent=1) + "\n")

    if args.name == "beacon":
        (ROOT / "keys" / "beacon.priv.hex").write_text(keys[0]["priv"].hex() + "\n")
        (ROOT / "keys" / "beacon.pub.hex").write_text(keys[0]["adv"].hex() + "\n")

    if not args.no_header:
        write_header(header_path, keys)
        (ROOT / "src" / "beacon_key.h").unlink(missing_ok=True)

    print(f"generated {len(keys)} keys for tag '{args.name}'")
    print(f"  store  : keys/{args.name}_keys.json")
    print(f"  header : {'(skipped)' if args.no_header else args.header}")
    print(f"slot 0 adv key  : {keys[0]['adv'].hex()}")
    print(f"slot 0 hash     : {hash_b64(keys[0]['adv'])}")
    print(f"slot 0 base64   : {base64.b64encode(keys[0]['adv']).decode()}")
    print()
    print(f"rotation period : 15 min x {len(keys)} = {len(keys) * 15 / 60:.0f} h before repeating")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
