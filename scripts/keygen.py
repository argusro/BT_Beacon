#!/usr/bin/env python3
"""
Generate a set of rotating Apple Find My advertising keys (P-224).

A real AirTag rotates its advertised key every ~15 minutes. We do the same with
a pre-generated ring of independent key pairs: the firmware walks the ring, and
the fetcher asks Apple for every hash in it, so no clock synchronisation is
needed between device and client.

Outputs
  src/beacon_keys.h      C array of N advertising keys (28 bytes each)
  keys/beacon_keys.json  private + advertising key per slot (SECRET)
  keys/beacon.priv.hex   slot 0 private key (compat with single-key tooling)
  keys/beacon.pub.hex    slot 0 advertising key

Usage:
    python scripts/keygen.py                 # 96 keys (~24h at 15 min)
    python scripts/keygen.py --count 288     # ~3 days
    python scripts/keygen.py --fresh         # do not reuse the current key
"""

import argparse
import base64
import hashlib
import json
import pathlib
import sys
from datetime import datetime, timezone

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = pathlib.Path(__file__).resolve().parent.parent
CURVE = ec.SECP224R1()


def hexdump(data: bytes, per_line: int = 14) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    return "\n".join(lines)


def adv_from_private(priv: bytes) -> bytes:
    pub = ec.derive_private_key(int.from_bytes(priv, "big"), CURVE).public_key()
    return pub.public_numbers().x.to_bytes(28, "big")


def hash_b64(adv: bytes) -> str:
    return base64.b64encode(hashlib.sha256(adv).digest()).decode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-n", "--count", type=int, default=96,
                        help="number of keys in the ring (default 96 = 24h at 15 min)")
    parser.add_argument("--fresh", action="store_true",
                        help="ignore the existing keys/beacon.priv.hex")
    args = parser.parse_args()

    if args.count < 2:
        parser.error("--count must be at least 2")

    keys: list[dict] = []

    # Slot 0 reuses the key the beacon already advertises, so reports filed
    # before the upgrade stay in the searched hash set.
    existing = ROOT / "keys" / "beacon.priv.hex"
    if existing.exists() and not args.fresh:
        priv = bytes.fromhex(existing.read_text().strip())
        if len(priv) == 28:
            keys.append({"priv": priv, "adv": adv_from_private(priv)})
            print(f"reusing existing key as slot 0 ({hash_b64(keys[0]['adv'])})")

    while len(keys) < args.count:
        key = ec.generate_private_key(CURVE)
        priv = key.private_numbers().private_value.to_bytes(28, "big")
        keys.append({"priv": priv, "adv": adv_from_private(priv)})

    # header
    entries = []
    for k in keys:
        entries.append("  {\n" + hexdump(k["adv"]) + "\n  },")
    header = (
        "// Generated by scripts/keygen.py -- do not edit by hand.\n"
        f"// {len(keys)} rotating Apple Find My advertising keys (P-224 X coordinates).\n"
        "#pragma once\n\n#include <stdint.h>\n\n"
        f"#define BEACON_KEY_COUNT {len(keys)}\n\n"
        f"static const uint8_t BEACON_KEYS[BEACON_KEY_COUNT][28] = {{\n"
        + "\n".join(entries) + "\n};\n"
    )
    (ROOT / "src" / "beacon_keys.h").write_text(header)
    (ROOT / "src" / "beacon_key.h").unlink(missing_ok=True)

    # key store (secret)
    (ROOT / "keys").mkdir(exist_ok=True)
    store = {
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "curve": "secp224r1",
        "keys": [
            {"priv": k["priv"].hex(), "adv": k["adv"].hex(), "hash_b64": hash_b64(k["adv"])}
            for k in keys
        ],
    }
    (ROOT / "keys" / "beacon_keys.json").write_text(json.dumps(store, indent=1) + "\n")
    (ROOT / "keys" / "beacon.priv.hex").write_text(keys[0]["priv"].hex() + "\n")
    (ROOT / "keys" / "beacon.pub.hex").write_text(keys[0]["adv"].hex() + "\n")

    print(f"generated {len(keys)} keys -> src/beacon_keys.h, keys/beacon_keys.json")
    print(f"slot 0 adv key  : {keys[0]['adv'].hex()}")
    print(f"slot 0 hash     : {hash_b64(keys[0]['adv'])}")
    print(f"slot 0 base64   : {base64.b64encode(keys[0]['adv']).decode()}")
    print()
    print(f"rotation period : {15} min x {len(keys)} = {len(keys) * 15 / 60:.0f} h before repeating")
    print("next: pio run -t upload, then rebuild devices.json with scripts/haystack_devices.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
