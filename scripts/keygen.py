#!/usr/bin/env python3
"""
Generate an Apple Find My / OpenHaystack advertising key pair (NIST P-224).

Why P-224? Its public-key X coordinate is exactly 28 bytes — the largest EC
key that fits in Apple's 31-byte Find My BLE advertisement.

Outputs
  keys/<name>.priv.hex   private scalar, 28 bytes  (SECRET - never flash this)
  keys/<name>.pub.hex    advertising key, 28 bytes  (public, goes on the device)
  src/beacon_key.h       C header consumed by the firmware

Usage
  python scripts/keygen.py [name]
"""

import base64
import pathlib
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = pathlib.Path(__file__).resolve().parent.parent


def hexdump(data: bytes, per_line: int = 8) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    return "\n".join(lines)


def main() -> int:
    name = sys.argv[1] if len(sys.argv) > 1 else "beacon"

    key = ec.generate_private_key(ec.SECP224R1())
    raw = key.public_key().public_bytes(
        serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
    )
    assert len(raw) == 57 and raw[0] == 0x04, "unexpected P-224 point encoding"
    adv_key = raw[1:29]  # X coordinate = the 28-byte advertising key

    (ROOT / "keys").mkdir(exist_ok=True)
    (ROOT / "keys" / f"{name}.priv.hex").write_text(
        key.private_numbers().private_value.to_bytes(28, "big").hex() + "\n"
    )
    (ROOT / "keys" / f"{name}.pub.hex").write_text(adv_key.hex() + "\n")

    header = f"""// Generated by scripts/keygen.py -- do not edit by hand.
// Apple Find My advertising key (P-224 X coordinate), 28 bytes.
#pragma once

#include <stdint.h>

static const uint8_t BEACON_ADV_KEY[28] = {{
{hexdump(adv_key)}
}};
"""
    (ROOT / "src" / "beacon_key.h").write_text(header)

    # Show what will actually be on the air.
    mac = bytearray(adv_key[:6])
    mac[0] |= 0xC0  # top two bits must be 0b11: static random address
    frame = [
        0x1e, 0xff, 0x4c, 0x00, 0x12, 0x19, 0x00,
        *adv_key[6:28],
        adv_key[0] >> 6,
        0x00,
    ]

    print(f"advertising key : {adv_key.hex()}")
    print(f"base64          : {base64.b64encode(adv_key).decode()}")
    print(f"BLE address     : {':'.join(f'{b:02x}' for b in mac)} (static random)")
    print(f"adv frame ({len(frame)}B): {' '.join(f'{b:02x}' for b in frame)}")
    print()
    print(f"wrote keys/{name}.priv.hex  (KEEP SECRET)")
    print(f"wrote keys/{name}.pub.hex")
    print("wrote src/beacon_key.h      (rebuild + upload to apply)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
